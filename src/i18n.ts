export type TKey = keyof Dict;
export const DICTS: Record<Lang, Dict> = { zh, en };

export function tr(lang: Lang, k: TKey) {
  return DICTS[lang][k];
}

export function useT() {
  const lang = useStore((s) => s.lang);
  return (k: TKey) => DICTS[lang][k];
}

export function nameOf(lang: Lang, x: { zh: string; en: string }) {
  return lang === 'zh' ? x.zh : x.en;
}
